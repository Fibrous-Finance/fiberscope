/**
 * A network's mark, centred in a box 1em square: 14px in the menu and beside the name in the
 * trigger, 12px where the trigger shows no name (the header's width rules set its font size).
 */
export function NetworkMark({
	id,
	className = "",
}: {
	id: NetworkId | UpcomingId;
	className?: string;
}) {
	const { viewBox, size, paths } = MARKS[id];
	const [, , width, height] = viewBox.split(" ").map(Number);
	// The long side, in ems of the box.
	const long = size / 14;
	return (
		<span
			aria-hidden="true"
			className={`grid size-[1em] flex-none place-items-center ${className}`}
		>
			<svg
				viewBox={viewBox}
				fill="currentColor"
				className="block"
				style={{
					width: `${width < height ? (long * width) / height : long}em`,
					height: `${width < height ? long : (long * height) / width}em`,
				}}
			>
				{paths.map(({ d, opacity }) => (
					<path key={d} d={d} opacity={opacity} />
				))}
			</svg>
		</span>
	);
}
